"""匯出 Python 參考實作的平均波浪漂移力夾具,供 C# WaveDriftTests 跨語言數值比對(docs/design/physics-waves.md 第 9 節)。

執行(自專案根目錄):
    cd src/Tools.Calibration && uv run python ../../tests/SimCore.Tests/Golden/export_waves_reference.py

輸出到本資料夾(tests/SimCore.Tests/Golden/):
    waves_force_table.csv   純函數取樣表:每列 (ship, loading, Hs, Tp, dir_deg, spectrum, gamma, depth_m, psi_deg, u, v) →
                            wavelength_m, factor(K), X_N, Y_N, N_Nm。C# 以同一船舶/裝載建立 WaveDriftModel 並以同狀態與水深呼叫
                            Compute,逐列相對差 ≤ 1e-12(兩種語言逐項同運算順序;只差 libm 末位)。
    waves_drift_run.yaml    積分案例情境(本腳本是唯一來源):FSB1 滿載 6 kn,Hs 2 m / Tp 7 s 自 045° 來、JONSWAP γ 3.3、水深 20 m
                            (深水波長 76.5 m → 水深 < λ0/2,走有限水深色散),100 s 右舵 10°,300 s。
    waves_drift_run.csv     ``#`` 標頭(產生指令、情境檔、末狀態雜湊、``# cmd: tick=<n> <JSON>``)之後每 1 s(50 tick)一列(含 tick 0):
                            tick,t,x,y,psi_deg,u,v,r,rpm,wave_X,wave_Y,wave_N,wavelength_m(步末狀態的漂移力 kN、kN·m 與峰值波長)。
                            C# 以同一份 YAML 建立 MMG 引擎推進並比對(位置差 / 航程 < 1%、各序列相對 < 1%,實際約 1e-10)。
``tests/test_waves.py`` 以同一路徑重算並比對(確定性)。
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from simosa_brm import __version__
from simosa_brm.external import DEG2RAD, Kin, WaveDriftModel
from simosa_brm.particulars import load_particulars
from simosa_brm.scenario import load_scenario, ship_from_scenario
from simosa_brm.server import SimServer

HERE = Path(__file__).resolve().parent
COMMAND = "cd src/Tools.Calibration && uv run python ../../tests/SimCore.Tests/Golden/export_waves_reference.py"
SAMPLE_EVERY = 50

# 純函數取樣表:船舶/裝載 × 浪 × 水深 × 狀態
SHIPS = (("FSB1", "full"), ("FSB1", "ballast"), ("FSB2", "full"))
WAVES = (
    {"significantHeight_m": 2.0, "peakPeriod_s": 7.0, "direction_deg": 90.0, "spectrum": "pm", "gamma": 3.3},
    {"significantHeight_m": 2.0, "peakPeriod_s": 7.0, "direction_deg": 45.0, "spectrum": "jonswap", "gamma": 3.3},
    {"significantHeight_m": 1.5, "peakPeriod_s": 9.0, "direction_deg": 0.0, "spectrum": "pm", "gamma": 3.3},
    {"significantHeight_m": 3.0, "peakPeriod_s": 10.0, "direction_deg": 225.0, "spectrum": "jonswap", "gamma": 2.0},
    {"significantHeight_m": 0.5, "peakPeriod_s": 5.0, "direction_deg": 180.0, "spectrum": "pm", "gamma": 3.3},
)
DEPTHS = (50.0, 12.0)
# (psi_deg, u, v)
STATES = ((0.0, 0.0, 0.0), (30.0, 3.0, 0.2), (200.0, -1.0, 0.0), (120.0, 6.0, -0.5))

RUN_CASE = {
    "name": "waves_drift_run",
    "title": "FSB1 滿載 6 kn、Hs 2 m / Tp 7 s 自 045° JONSWAP、水深 20 m,100 s 右舵 10°(300 s)",
    "duration_s": 300.0,
    "yaml": """\
seed: 1
ship: { id: FSB1, loading: full }
origin: { lat: 23.80, lon: 120.15 }
initial: { position: { x: 0, y: 0 }, heading: 0, speed: 6, telegraph: HAH }
environment:
  wind: { trueSpeed: 0, trueDir: 0, gustiness: 0 }
  current: { set: 0, drift: 0 }
  waterDepth: 20
  waves: { significantHeight_m: 2.0, peakPeriod_s: 7.0, direction_deg: 45, spectrum: jonswap, gamma: 3.3 }
""",
    "commands": [
        (5000, {"type": "rudder", "value": 10}),
    ],
}


def force_table_rows() -> list[tuple]:
    rows: list[tuple] = []
    for ship_id, loading in SHIPS:
        raw = load_particulars(ship_id, loading).raw
        for w in WAVES:
            model = WaveDriftModel(raw, loading, w)
            for depth in DEPTHS:
                for psi_deg, u, v in STATES:
                    r = model.compute(Kin(0.0, 0.0, psi_deg * DEG2RAD, u, v, 0.0), depth)
                    rows.append((ship_id, loading, w["significantHeight_m"], w["peakPeriod_s"], w["direction_deg"], w["spectrum"], w["gamma"],
                                 depth, psi_deg, u, v, r.wavelength, r.factor, r.X, r.Y, r.N))
    return rows


def write_force_table() -> Path:
    out = HERE / "waves_force_table.csv"
    lines = [
        f"# generated by export_waves_reference.py (simosa_brm {__version__}); do not edit",
        f"# command: {COMMAND}",
        "ship,loading,Hs,Tp,dir_deg,spectrum,gamma,depth_m,psi_deg,u,v,wavelength_m,factor,X_N,Y_N,N_Nm",
    ]
    for row in force_table_rows():
        lines.append(",".join(v if isinstance(v, str) else repr(float(v)) for v in row))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return out


def _sample(ship) -> str:
    s = ship.state
    r = ship.waves.last
    vals = [s.tick, s.t, s.x, s.y, math.degrees(s.psi) % 360.0, s.u, s.v, s.r, s.n * 60.0, r.X / 1000.0, r.Y / 1000.0, r.N / 1000.0, r.wavelength]
    return ",".join(repr(int(v)) if i == 0 else repr(float(v)) for i, v in enumerate(vals))


def run_case(case: dict, write: bool = True) -> dict:
    """執行積分案例;回傳 {rows, hash, ship}(測試也用此函式檢查可重現性)。"""
    yaml_path = HERE / f"{case['name']}.yaml"
    text = f"# 由 export_waves_reference.py 產生(請勿手改):{case['title']}\nid: {case['name']}\n" + case["yaml"]
    if write:
        yaml_path.write_text(text, encoding="utf-8", newline="\n")
    sc = load_scenario(yaml_path)
    ship = ship_from_scenario(sc, dt=0.02)
    srv = SimServer(ship, scenario=sc)
    cmds = sorted(case["commands"], key=lambda c: c[0])
    rows = [_sample(ship)]
    steps = int(round(case["duration_s"] / ship.dt))
    ci = 0
    for _ in range(steps):
        while ci < len(cmds) and cmds[ci][0] == ship.state.tick:
            ack = srv.apply_command(cmds[ci][1])
            if not ack["ok"]:
                raise RuntimeError(f"{case['name']} tick {ship.state.tick} 指令失敗:{ack}")
            ci += 1
        ship.step()
        if ship.state.tick % SAMPLE_EVERY == 0:
            rows.append(_sample(ship))
    if ci != len(cmds):
        raise RuntimeError(f"{case['name']}:有指令未執行")
    return {"rows": rows, "hash": ship.state_hash(), "ship": ship}


def write_run(case: dict) -> Path:
    res = run_case(case)
    ship = res["ship"]
    header = [
        f"# simosa_brm {__version__} 參考實作匯出(波浪漂移力):{case['title']}",
        f"# command: {COMMAND}",
        f"# scenario: {case['name']}.yaml",
        f"# coefficients: data/ships/FSB1/coefficients.full.json (method={ship.c['source']['method']}, generatedAt={ship.c['generatedAt']})",
        f"# state_hash_end: {res['hash']}",
    ]
    for tick, cmd in sorted(case["commands"], key=lambda c: c[0]):
        header.append(f"# cmd: tick={tick} {json.dumps(cmd, ensure_ascii=False, separators=(',', ':'))}")
    cols = ["tick", "t", "x", "y", "psi_deg", "u", "v", "r", "rpm", "wave_X", "wave_Y", "wave_N", "wavelength_m"]
    path = HERE / f"{case['name']}.csv"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header) + "\n")
        f.write(",".join(cols) + "\n")
        f.write("\n".join(res["rows"]) + "\n")
    s = ship.state
    print(f"已寫入 {path.name}({len(res['rows'])} 列;末狀態 x={s.x:.1f} y={s.y:.1f} psi={math.degrees(s.psi) % 360:.1f}° u={s.u:.2f} v={s.v:.3f})")
    return path


if __name__ == "__main__":
    print(write_force_table())
    write_run(RUN_CASE)
