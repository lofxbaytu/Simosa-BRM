"""匯出 Python 參考實作的時變流場夾具(流向/流速與東/北分量對練習時間),供 C# TidalStreamTests 跨語言數值比對(1e-9;
docs/design/scenario-engine.md 第 1.5.2 節:流向/流速只由 t = tick·dt 決定;表為向量內插、潮流由潮高變化率決定)。

執行(自專案根目錄):
    cd src/Tools.Calibration && uv run python ../../tests/SimCore.Tests/Golden/export_current_reference.py

輸出到本資料夾(tests/SimCore.Tests/Golden/):
    current_table.csv / current_tidal.csv:``#`` 開頭的標頭列(產生指令、情境檔),之後為 CSV:
    tick,t,set_deg,drift_kn,east_mps,north_mps,currentSource
    以 ``ship_from_scenario`` 建立模型後逐步推進(state_json 的 current.set / current.drift / currentSource;東/北分量為 env.current_en),
    在 TICKS 列出的 tick 取樣(含 tick 0)。
``tests/test_current.py`` 以同一路徑重算並比對(確定性),C# TidalStreamTests 以 SimulationEngine 推進到同 tick 比對 BuildState()。

    current_field.csv(空間變化流場 field + timeScale tidal;C# CurrentFieldTests.GoldenFieldMatchesPythonReference):
    kind,tick,t,x,y,set_deg,drift_kn,east_mps,north_mps,currentSource
    kind = run:船模推進到 tick 的自船位置 (x, y) 與 state.current / env.current_en(自船位置的值);
    kind = point(tick = −1):不經船模,直接以 ``CurrentField.at(t, x, y)`` 與 ``MMGShip.current_en_at(t, x, y)`` 在 POINTS 列出的
    (t, x, y) 取樣(角點、格中、格外、平潮與中退時刻)。C# 以 ``CurrentModel.At(t, x, y)`` / ``EnvironmentConditions.CurrentVectorAt`` 比對 1e-9。
"""

from __future__ import annotations

import math
from pathlib import Path

from simosa_brm import __version__
from simosa_brm.current import KN_TO_MPS
from simosa_brm.scenario import load_scenario, ship_from_scenario

HERE = Path(__file__).resolve().parent
CASES = ("current_table", "current_tidal")
# 取樣 tick(含表的端點外、內插段中間、方向跨 360° 段、轉流前後、非整秒;3000 tick = 60 s)
TICKS = (0, 1, 7, 50, 123, 250, 499, 500, 1275, 1500, 2275, 2500, 2700, 2780, 2800, 2999, 3000)


def sample_case(name: str) -> list[tuple[int, float, float, float, float, float, str]]:
    """依情境推進到 TICKS 的各 tick,回傳 (tick, t, set_deg, drift_kn, east_mps, north_mps, currentSource)。"""
    sc = load_scenario(HERE / f"{name}.yaml")
    ship = ship_from_scenario(sc)
    rows: list[tuple[int, float, float, float, float, float, str]] = []
    for tick in sorted(set(TICKS)):
        while ship.state.tick < tick:
            ship.step()
        st = ship.state_json()
        e, n = ship.env.current_en
        rows.append((tick, tick * ship.dt, st["current"]["set"], st["current"]["drift"], e, n, st["currentSource"]))
    return rows


def write_case(name: str) -> Path:
    rows = sample_case(name)
    out = HERE / f"{name}.csv"
    lines = [
        f"# generated by export_current_reference.py (simosa_brm {__version__}); do not edit",
        f"# scenario: {name}.yaml",
        "tick,t,set_deg,drift_kn,east_mps,north_mps,currentSource",
    ]
    lines += [f"{tick},{t!r},{s!r},{d!r},{e!r},{n!r},{src}" for tick, t, s, d, e, n, src in rows]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


# 空間變化流場夾具的直接取樣點 (t, x, y):角點、格中、格內非整點、平潮(t = 20,比例 0)、中退(t = 50)、格外(邊緣值)、邊界上
FIELD_CASE = "current_field"
POINTS = (
    (0.0, -200.0, -100.0), (0.0, 200.0, 200.0), (5.5, -150.0, -50.0), (5.5, 50.0, 150.0), (12.34, 12.5, 37.5),
    (20.0, 0.0, 0.0), (50.0, 0.0, 0.0), (50.0, -500.0, 0.0), (50.0, 0.0, 500.0), (50.0, 300.0, -300.0),
    (110.0, 199.99, 199.99), (33.3, -200.0, 123.4), (33.3, 77.7, -100.0),
)


def sample_field_case(name: str = FIELD_CASE) -> list[tuple[str, int, float, float, float, float, float, float, float, str]]:
    """run 列(TICKS 的自船位置與流)與 point 列(POINTS 的直接取樣)。"""
    sc = load_scenario(HERE / f"{name}.yaml")
    ship = ship_from_scenario(sc)
    model = ship.current_model
    assert model is not None and model.spatially_varying
    rows: list[tuple[str, int, float, float, float, float, float, float, float, str]] = []
    for tick in sorted(set(TICKS)):
        while ship.state.tick < tick:
            ship.step()
        st = ship.state_json()
        e, n = ship.env.current_en
        rows.append(("run", tick, tick * ship.dt, ship.state.x, ship.state.y, st["current"]["set"], st["current"]["drift"], e, n, st["currentSource"]))
    for t, x, y in POINTS:
        set_rad, drift = model.at(t, x, y)
        e, n = ship.current_en_at(t, x, y)
        rows.append(("point", -1, t, x, y, math.degrees(set_rad) % 360.0, drift / KN_TO_MPS, e, n, model.source))
    return rows


def write_field_case(name: str = FIELD_CASE) -> Path:
    rows = sample_field_case(name)
    out = HERE / f"{name}.csv"
    lines = [
        f"# generated by export_current_reference.py (simosa_brm {__version__}); do not edit",
        f"# scenario: {name}.yaml",
        "kind,tick,t,x,y,set_deg,drift_kn,east_mps,north_mps,currentSource",
    ]
    lines += [f"{kind},{tick},{t!r},{x!r},{y!r},{s!r},{d!r},{e!r},{n!r},{src}" for kind, tick, t, x, y, s, d, e, n, src in rows]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    for case in CASES:
        print(write_case(case))
    print(write_field_case())
