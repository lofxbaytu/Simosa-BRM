"""匯出 Python 參考實作的潮汐夾具(潮高與有效水深對練習時間),供 C# TideTests 跨語言數值比對(1e-9;
docs/design/scenario-engine.md 第 1.5.1 節:有效水深 = 基底水深 + 潮高(t),潮高只由 t = tick·dt 決定)。

執行(自專案根目錄):
    cd src/Tools.Calibration && uv run python ../../tests/SimCore.Tests/Golden/export_tide_reference.py

輸出到本資料夾(tests/SimCore.Tests/Golden/):
    tide_table.csv / tide_harmonic.csv:``#`` 開頭的標頭列(產生指令、情境檔),之後為 CSV:tick,t,tideHeight_m,waterDepth_m
    以 ``ship_from_scenario`` 建立模型後逐步推進(state_json 的 tideHeight_m / waterDepth),在 TICKS 列出的 tick 取樣(含 tick 0)。
``tests/test_tide.py`` 以同一路徑重算並比對(確定性),C# TideTests 以 SimulationEngine 推進到同 tick 比對 BuildState()。
"""

from __future__ import annotations

from pathlib import Path

from simosa_brm import __version__
from simosa_brm.scenario import load_scenario, ship_from_scenario

HERE = Path(__file__).resolve().parent
CASES = ("tide_table", "tide_harmonic")
# 取樣 tick(含表的端點外、內插段中間、非整秒;3000 tick = 60 s)
TICKS = (0, 1, 7, 50, 123, 499, 500, 1275, 1500, 2275, 2500, 2999, 3000)


def sample_case(name: str) -> list[tuple[int, float, float, float]]:
    """依情境推進到 TICKS 的各 tick,回傳 (tick, t, tideHeight_m, waterDepth_m)。"""
    sc = load_scenario(HERE / f"{name}.yaml")
    ship = ship_from_scenario(sc)
    rows: list[tuple[int, float, float, float]] = []
    want = sorted(set(TICKS))
    for tick in want:
        while ship.state.tick < tick:
            ship.step()
        st = ship.state_json()
        rows.append((tick, tick * ship.dt, st["tideHeight_m"], st["waterDepth"]))
    return rows


def write_case(name: str) -> Path:
    rows = sample_case(name)
    out = HERE / f"{name}.csv"
    lines = [
        f"# generated by export_tide_reference.py (simosa_brm {__version__}); do not edit",
        f"# scenario: {name}.yaml",
        "tick,t,tideHeight_m,waterDepth_m",
    ]
    lines += [f"{tick},{t!r},{h!r},{d!r}" for tick, t, h, d in rows]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    for case in CASES:
        print(write_case(case))
