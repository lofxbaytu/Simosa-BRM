"""匯出 Python 參考實作的區域水深覆寫夾具(位置 → 有效水深),供 C# ZoneDepthTests 跨語言數值比對(1e-9;
docs/design/scenario-engine.md 第 4.3 節:自船在 zones[].waterDepth_m 多邊形內時基底改取區域值(多區取最淺),再加潮高(t);
depth.py 與 C# DepthProviders.cs ZoneDepth / Polygon2D.Contains 同演算法與邊界規則:邊上(距離 < 1e-9 m)視為內)。

執行(自專案根目錄):
    cd src/Tools.Calibration && uv run python ../../tests/SimCore.Tests/Golden/export_zone_depth_reference.py

輸出到本資料夾(tests/SimCore.Tests/Golden/):
    zone_depth.csv:``#`` 開頭的標頭列(產生指令、情境檔),之後為 CSV:x,y,waterDepth_m
    以 ``ship_from_scenario`` 建立模型(tick 0;潮高 = 情境 tide 於 t = 0),對 POINTS 的每個 ENU 位置取 ``MMGShip.depth_at(x, y)``。
    取樣點涵蓋:重疊區(最淺)、單一區、邊上、頂點、凹多邊形的內/缺口/凹頂點、與頂點同 y 的區外點、1e-9 門檻內外、
    比基底深的區域(不覆寫)、無 waterDepth_m 的區域、非 ukcPolicy 型別的區域、經緯度頂點區域(取樣點由 Python LocalTangentPlane 換算,遠離邊)。
``tests/test_zone_depth.py`` 以同一路徑重算並比對(確定性),C# ZoneDepthTests 以 SimulationEngine.Environment.DepthAt(x, y) 比對。
"""

from __future__ import annotations

from pathlib import Path

from simosa_brm import __version__
from simosa_brm.scenario import load_scenario, ship_from_scenario

HERE = Path(__file__).resolve().parent
CASE = "zone_depth"
# (x, y) ENU;None 表示由經緯度換算(區域 E 的內點)
POINTS: tuple[tuple[float, float] | tuple[str, float, float], ...] = (
    (0.0, 0.0),                   # A ∩ B → 8(最淺)
    (-200.0, -200.0),             # A → 12
    (500.0, 500.0),               # B → 8
    (-300.0, 0.0),                # A 左邊上 → 12
    (300.0, 300.0),               # A 頂點、B 內 → 8
    (-300.000001, 0.0),           # A 左邊外 1 µm → 基底 25
    (-299.9999999995, 0.0),       # A 左邊內側 5e-10 m(< 1e-9 門檻,邊上視為內)→ 12
    (0.0, 300.0),                 # A 上邊上、B 內 → 8
    (600.0, 600.0),               # B 頂點 → 8
    (650.0, 650.0),               # B 外 → 25
    (-800.0, -800.0),             # C(凹多邊形)內 → 15
    (-600.0, -600.0),             # C 缺口(區外)→ 25
    (-600.0, -800.0),             # C 下臂內 → 15
    (-700.0, -700.0),             # C 凹頂點(邊上)→ 15
    (-700.0, -900.0),             # C 下邊上 → 15
    (-1000.0, -900.0),            # 與 C 頂點同 y 的區外點(ray casting 邊界情況)→ 25
    (1200.0, 0.0),                # D(40 m,比基底深)內 → 25
    (-1800.0, -1800.0),           # F(noGo、無 waterDepth_m)內 → 25
    (800.0, 800.0),               # G(reporting,6 m)內 → 6
    ("latlon", 23.8065, 120.160), # E(經緯度頂點)內 → 10
    (-1500.0, 0.0),               # 初始位置,區外 → 25
    (2000.0, 2000.0),             # 區外 → 25
)


def sample_case() -> list[tuple[float, float, float]]:
    """依情境建立模型(tick 0),回傳每個取樣位置的 (x, y, 有效水深)。"""
    sc = load_scenario(HERE / f"{CASE}.yaml")
    ship = ship_from_scenario(sc)
    rows: list[tuple[float, float, float]] = []
    for p in POINTS:
        if p[0] == "latlon":
            x, y = ship.ltp.to_local(float(p[1]), float(p[2]))
        else:
            x, y = float(p[0]), float(p[1])
        d = ship.depth_at(x, y)
        assert d is not None
        rows.append((x, y, d))
    return rows


def write_case() -> Path:
    rows = sample_case()
    out = HERE / f"{CASE}.csv"
    lines = [
        f"# generated by export_zone_depth_reference.py (simosa_brm {__version__}); do not edit",
        f"# scenario: {CASE}.yaml",
        "x,y,waterDepth_m",
    ]
    lines += [f"{x!r},{y!r},{d!r}" for x, y, d in rows]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    print(write_case())
